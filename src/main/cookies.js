'use strict';

const fs = require('fs');
const path = require('path');
const { session } = require('electron');

const BROWSER_PARTITION = 'persist:honk-browser';

function netscapeLine(cookie) {
  if (!cookie || !cookie.domain) return null;

  const name = String(cookie.name || '');
  const value = String(cookie.value || '');
  if (/[\t\r\n]/.test(name + value)) return null;

  const expired = cookie.expirationDate && cookie.expirationDate < Date.now() / 1000;
  if (expired) return null;

  const domain = `${cookie.httpOnly ? '#HttpOnly_' : ''}${cookie.domain}`;
  const includeSubdomains = cookie.domain.startsWith('.') ? 'TRUE' : 'FALSE';
  const cookiePath = cookie.path || '/';
  const secure = cookie.secure ? 'TRUE' : 'FALSE';
  const expiry = Math.floor(cookie.expirationDate || 0);

  return [domain, includeSubdomains, cookiePath, secure, expiry, name, value].join('\t');
}

async function exportCookies(targetFile) {
  const browserSession = session.fromPartition(BROWSER_PARTITION);
  const cookies = await browserSession.cookies.get({});

  const lines = [
    '# Netscape HTTP Cookie File',
    '# Generated by Honk Downloader',
    ''
  ];

  for (const cookie of cookies) {
    const line = netscapeLine(cookie);
    if (line) lines.push(line);
  }

  fs.mkdirSync(path.dirname(targetFile), { recursive: true });
  fs.writeFileSync(targetFile, `${lines.join('\n')}\n`, { encoding: 'utf8', mode: 0o600 });

  return {
    path: targetFile,
    count: lines.length - 3
  };
}

module.exports = {
  BROWSER_PARTITION,
  exportCookies
};
