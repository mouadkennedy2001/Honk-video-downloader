  function register(dict) {
    if (!dict || typeof dict !== 'object') return;
    for (const code of Object.keys(dict)) {
      const entry = dict[code];
      if (!entry || typeof entry !== 'object') continue;
      TRANSLATIONS[code] = { ...EN, ...entry };
      if (!LANGUAGE_OPTIONS.some((option) => option.value === code)) {
        LANGUAGE_OPTIONS.push({
          value: code,
          label: `${entry.langName || code} — ${LANGUAGE_NAMES[code] || code.toUpperCase()}`
        });
      }
    }
  }

